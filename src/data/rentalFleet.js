export const formatRentalSpec = (car) => {
  const parts = [];
  if (car.exterior) parts.push(`${car.exterior} exterior`);
  if (car.interior) parts.push(`${car.interior} interior`);
  if (car.notes) parts.push(car.notes);
  return parts.join(' · ');
};

